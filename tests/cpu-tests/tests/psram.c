#include "trap.h"
#include "peripheral/test_intf.h"

static inline uint8_t  inb(uintptr_t addr) { return *(volatile uint8_t  *)addr; }
static inline uint16_t inw(uintptr_t addr) { return *(volatile uint16_t *)addr; }
static inline uint32_t inl(uintptr_t addr) { return *(volatile uint32_t *)addr; }
static inline uint64_t inll(uintptr_t addr) { return *(volatile uint64_t *)addr; }
static inline void outb(uintptr_t addr, uint8_t data) { *(volatile uint8_t *)addr = data; }
static inline void outw(uintptr_t addr, uint16_t data) { *(volatile uint16_t *)addr = data; }
static inline void outl(uintptr_t addr, uint32_t data) { *(volatile uint32_t *)addr = data; }

#define CHECK_DATA(a,b) do{if((a)!=(b)) halt((int)b);}while(0)

int main() {
    test_intf_switch_psram(1);

    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x0), 0x30);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x1), 0x31);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x2), 0x32);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x3), 0x33);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x4), 0x34);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x5), 0x35);
    
    CHECK_DATA(inw(TEST_INIF_PSRAM_BASEADDR+0x0), 0x3130);
    CHECK_DATA(inw(TEST_INIF_PSRAM_BASEADDR+0x1), 0x3231);
    CHECK_DATA(inw(TEST_INIF_PSRAM_BASEADDR+0x2), 0x3332);
    CHECK_DATA(inw(TEST_INIF_PSRAM_BASEADDR+0x3), 0x3433);
    CHECK_DATA(inw(TEST_INIF_PSRAM_BASEADDR+0x4), 0x3534);
    CHECK_DATA(inw(TEST_INIF_PSRAM_BASEADDR+0x5), 0x3635);

    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x0), 0x33323130);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x1), 0x34333231);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x2), 0x35343332);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x3), 0x36353433);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x4), 0x37363534);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x5), 0x38373635);
    
    outb(TEST_INIF_PSRAM_BASEADDR+0x0, 0x50);
    outb(TEST_INIF_PSRAM_BASEADDR+0x1, 0x51);
    outb(TEST_INIF_PSRAM_BASEADDR+0x2, 0x52);
    outb(TEST_INIF_PSRAM_BASEADDR+0x3, 0x53);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x0), 0x53525150);
    
    outb(TEST_INIF_PSRAM_BASEADDR+0x4, 0x54);
    outb(TEST_INIF_PSRAM_BASEADDR+0x5, 0x55);
    outb(TEST_INIF_PSRAM_BASEADDR+0x6, 0x56);
    outb(TEST_INIF_PSRAM_BASEADDR+0x7, 0x57);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x4), 0x57565554);
    
    outw(TEST_INIF_PSRAM_BASEADDR+0x0, 0x5150);
    outw(TEST_INIF_PSRAM_BASEADDR+0x2, 0x5352);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x0), 0x53525150);
    
    outw(TEST_INIF_PSRAM_BASEADDR+0x1, 0x5251);
    outw(TEST_INIF_PSRAM_BASEADDR+0x3, 0x5453);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x1), 0x54535251);
    
    outw(TEST_INIF_PSRAM_BASEADDR+0x2, 0x5352);
    outw(TEST_INIF_PSRAM_BASEADDR+0x4, 0x5554);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x2), 0x55545352);
    
    outw(TEST_INIF_PSRAM_BASEADDR+0x3, 0x5453);
    outw(TEST_INIF_PSRAM_BASEADDR+0x5, 0x5655);
    CHECK_DATA(inl(TEST_INIF_PSRAM_BASEADDR+0x3), 0x56555453);

    outl(TEST_INIF_PSRAM_BASEADDR+0x0, 0x53525150);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x0), 0x50);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x1), 0x51);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x2), 0x52);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x3), 0x53);

    outl(TEST_INIF_PSRAM_BASEADDR+0x1, 0x54535251);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x1), 0x51);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x2), 0x52);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x3), 0x53);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x4), 0x54);

    outl(TEST_INIF_PSRAM_BASEADDR+0x2, 0x55545352);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x2), 0x52);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x3), 0x53);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x4), 0x54);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x5), 0x55);
    
    outl(TEST_INIF_PSRAM_BASEADDR+0x3, 0x56555453);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x3), 0x53);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x4), 0x54);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x5), 0x55);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0x6), 0x56);

    outl(TEST_INIF_PSRAM_BASEADDR+0xa83, 0x36303332);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0xa83), 0x32);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0xa84), 0x33);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0xa85), 0x30);
    CHECK_DATA(inb(TEST_INIF_PSRAM_BASEADDR+0xa86), 0x36);

    return 0;
}
